<?php
declare(strict_types=1);

/**
 * One-time web installer (for cPanel users without SSH).
 * Writes config/config.php, creates all tables and the Super Admin account.
 * Protection: it refuses to run once config/config.php or storage/installed.lock exists, the form carries a
 * one-time CSRF token, and failed attempts are throttled. Delete install.php after installing.
 */
define('CNX_INSTALLER', true);
require __DIR__ . '/includes/bootstrap.php';

$configFile = CNX_ROOT . '/config/config.php';
$lockFile = CNX_ROOT . '/storage/installed.lock';
$installed = is_file($configFile) || is_file($lockFile);
if ($installed && $_SERVER['REQUEST_METHOD'] === 'POST') {
    http_response_code(403);
    exit('ClassNex is already installed.');
}
session_name('CNXINSTALL');
session_start(['cookie_httponly' => true, 'cookie_samesite' => 'Strict']);
$_SESSION['install_csrf'] ??= bin2hex(random_bytes(16));
$_SESSION['install_tries'] ??= 0;
$errors = [];
$done = false;

$checks = [
    'PHP 8.2 or newer'            => version_compare(PHP_VERSION, '8.2.0', '>='),
    'PDO MySQL extension'         => extension_loaded('pdo_mysql'),
    'Sodium (encryption)'         => extension_loaded('sodium'),
    'GD (image processing)'       => extension_loaded('gd'),
    'cURL (WhatsApp, FCM, payments)' => extension_loaded('curl'),
    'mbstring'                    => extension_loaded('mbstring'),
    'OpenSSL'                     => extension_loaded('openssl'),
    'Zip (Excel export)'          => extension_loaded('zip'),
    'fileinfo'                    => extension_loaded('fileinfo'),
    'config/ is writable'         => is_writable(CNX_ROOT . '/config'),
    'storage/ is writable'        => is_writable(CNX_ROOT . '/storage'),
    'uploads/ is writable'        => is_writable(CNX_ROOT . '/uploads'),
];
$allOk = !in_array(false, $checks, true);

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST' && $allOk) {
    if (!hash_equals($_SESSION['install_csrf'], (string) ($_POST['csrf'] ?? '')) || $_SESSION['install_tries']++ > 10) {
        http_response_code(403);
        exit('Installer session expired. Reload the page and try again.');
    }
    $in = array_map(static fn($v) => is_string($v) ? trim($v) : $v, $_POST);
    $scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
    $appUrl = rtrim($in['app_url'] ?: $scheme . '://' . ($_SERVER['HTTP_HOST'] ?? 'localhost') . rtrim(dirname($_SERVER['SCRIPT_NAME']), '/'), '/');
    if (!filter_var($in['admin_email'] ?? '', FILTER_VALIDATE_EMAIL)) {
        $errors[] = 'Enter a valid admin email.';
    }
    if (strlen($in['admin_password'] ?? '') < 8 || !preg_match('/[A-Za-z]/', $in['admin_password']) || !preg_match('/\d/', $in['admin_password'])) {
        $errors[] = 'Admin password must be at least 8 characters with letters and numbers.';
    }
    $cfg = [
        'env' => 'production', 'debug' => false, 'app_url' => $appUrl, 'timezone' => 'Asia/Kolkata',
        'db' => ['host' => $in['db_host'] ?: 'localhost', 'port' => (int) ($in['db_port'] ?: 3306), 'name' => $in['db_name'], 'user' => $in['db_user'], 'pass' => $in['db_pass'] ?? '', 'charset' => 'utf8mb4'],
        'app_key' => base64_encode(random_bytes(32)), 'session_name' => 'CNXSESS', 'token_ttl_days' => 30, 'session_ttl_hours' => 12,
        'storage_path' => CNX_ROOT . '/storage', 'cron_http_key' => bin2hex(random_bytes(16)),
    ];
    if (!$errors) {
        try {
            Config::load($cfg);
            DB::reset();
            DB::pdo();
            Migrator::run();
            $exists = DB::val("SELECT id FROM users WHERE role = 'super_admin' AND email = ?", [strtolower($in['admin_email'])]);
            if (!$exists) {
                DB::insert('users', ['role' => 'super_admin', 'name' => $in['admin_name'] ?: 'Super Admin', 'email' => strtolower($in['admin_email']), 'mobile' => Phone::normalize($in['admin_mobile'] ?? '') ?: null, 'password_hash' => password_hash($in['admin_password'], PASSWORD_DEFAULT), 'status' => 'active']);
            }
            Settings::set('support_email', $in['admin_email']);
            $php = "<?php\n// Generated by ClassNex installer on " . date('c') . "\n// KEEP THIS FILE PRIVATE. Back up app_key: without it encrypted documents cannot be read.\nreturn " . var_export($cfg, true) . ";\n";
            if (file_put_contents($configFile, $php, LOCK_EX) === false) {
                throw new RuntimeException('Could not write config/config.php');
            }
            @chmod($configFile, 0640);
            file_put_contents($lockFile, 'Installed ' . date('c') . "\n");
            $done = true;
            unset($_SESSION['install_csrf']);
        } catch (Throwable $e) {
            $errors[] = 'Installation failed: ' . $e->getMessage();
        }
    }
}
